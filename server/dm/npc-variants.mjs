// 随机抽取一套变体（在线LLM失败/离线时使用）；每个NPC 50%概率采用备用文案（原版/变体穿插，不同冒险组合不同）
export function randomNpcVariants(rndFn) {
  const r = rndFn || Math.random;
  const out = {};
  for (const [npcId, v] of Object.entries(NPC_VARIANTS)) {
    const useAlt = r() < 0.5;
    const options = {};
    for (const [oid, arr] of Object.entries(v.options || {})) {
      options[oid] = useAlt && arr?.length ? arr[0] : null;
    }
    const results = {};
    for (const [oid, arr] of Object.entries(v.results || {})) {
      results[oid] = useAlt && arr?.length ? arr[0] : null;
    }
    out[npcId] = {
      greet: useAlt && v.greet?.length ? v.greet[0] : null,
      options,
      results,
    };
  }
  return out;
}
